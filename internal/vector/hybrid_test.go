// rrfScores flattens a fused ranking into a map of ID → score.
func rrfScores(fused []rrfItem) map[string]float64 {
	out := make(map[string]float64, len(fused))
	for _, it := range fused {
		out[it.ID] = it.Score
	}
	return out
}

// rrfIDs extracts just the IDs in ranking order.
func rrfIDs(fused []rrfItem) []string {
	out := make([]string, 0, len(fused))
	for _, it := range fused {
		out = append(out, it.ID)
	}
	return out
}

// rrfResultIDs extracts the chunk IDs from a slice of
// SearchResults.
func rrfResultIDs(results []searchHybridResult) []string {
	out := make([]string, 0, len(results))
	for _, r := range results {
		out = append(out, r.ChunkID)
	}
	sort.Strings(out)
	return out
}

// indexOf returns the index of needle in haystack, or -1.
func indexOf(haystack []string, needle string) int {
	for i, s := range haystack {
		if s == needle {
			return i
		}
	}
	return -1
}
