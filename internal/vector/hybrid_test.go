// Test the RRF helper in isolation. Fusion is the heart of
// the hybrid path; getting it wrong silently degrades search
// quality, so we pin its behavior here.

// Identical rankings from both sides → fused score is twice
// the single-side score for every document.
func TestRRF_IdenticalRankings(t *testing.T) {
	t.Parallel()

	semantic := []string{"a", "b", "c"}
	keyword := []string{"a", "b", "c"}
	got := rrfFuse(semantic, keyword, 60)

	require.Len(t, got, 3)
	// a ranks #1 in both → highest fused score.
	scores := rrfScores(got)
	assert.Greater(t, scores["a"], scores["b"])
	assert.Greater(t, scores["b"], scores["c"])
}

// Documents that appear in BOTH rankings should rank
// higher than documents that appear in only one.
func TestRRF_OverlapBeatsSingleSource(t *testing.T) {
	t.Parallel()

	semantic := []string{"a", "x", "y"}
	keyword := []string{"a", "b", "c"}
	got := rrfFuse(semantic, keyword, 60)
	scores := rrfScores(got)

	// 'a' is in both lists (top of both); x/y/b/c appear
	// in only one. 'a' must rank above any of them.
	assert.Greater(t, scores["a"], scores["x"], "'a' should beat a single-source hit")
	assert.Greater(t, scores["a"], scores["b"])
	assert.Greater(t, scores["a"], scores["c"])
	assert.Greater(t, scores["a"], scores["y"])
}

// Documents that appear in NEITHER ranking must not appear
// in the fused result. Defensive: callers can pass empty
// rankings without us emitting bogus IDs.
func TestRRF_NoCrossListPollution(t *testing.T) {
	t.Parallel()

	semantic := []string{"a", "b"}
	keyword := []string{"c", "d"}
	got := rrfFuse(semantic, keyword, 60)
	ids := rrfIDs(got)

	// All four IDs should be present (two from each side).
	assert.ElementsMatch(t, []string{"a", "b", "c", "d"}, ids)
}

// RRF is deterministic — same input always yields the same
// fused ranking. Critical property: callers must not get
// different results on consecutive identical queries.
func TestRRF_Deterministic(t *testing.T) {
	t.Parallel()

	semantic := []string{"a", "b", "c", "d"}
	keyword := []string{"d", "c", "b", "a"}

	first := rrfFuse(semantic, keyword, 60)
	second := rrfFuse(semantic, keyword, 60)

	require.Len(t, first, len(second))
	for i := range first {
		assert.Equal(t, first[i].ID, second[i].ID,
			"position %d must match across runs", i)
		assert.InDelta(t, first[i].Score, second[i].Score, 1e-9)
	}
}

// The k constant only affects the absolute score scale; the
// ranking should be invariant to k. This is the property
// that lets us pick k=60 as a default without tuning.
func TestRRF_KInvariant(t *testing.T) {
	t.Parallel()

	semantic := []string{"a", "b", "c"}
	keyword := []string{"b", "a", "c"}

	at60 := rrfIDs(rrfFuse(semantic, keyword, 60))
	at1 := rrfIDs(rrfFuse(semantic, keyword, 1))
	at1000 := rrfIDs(rrfFuse(semantic, keyword, 1000))

	assert.Equal(t, at60, at1, "k must not change ranking")
	assert.Equal(t, at60, at1000)
}

// Empty rankings are tolerated (no panic, empty result).
// Hits present in ONE ranking still surface — only when
// BOTH rankings are empty does the fused result become empty.
func TestRRF_EmptyRankings(t *testing.T) {
	t.Parallel()

	assert.Empty(t, rrfFuse(nil, nil, 60))
	assert.Empty(t, rrfFuse([]string{}, []string{}, 60))
	assert.Len(t, rrfFuse([]string{"a"}, nil, 60), 1,
		"hits in one ranking must still surface")
	assert.Len(t, rrfFuse(nil, []string{"a"}, 60), 1,
		"hits in one ranking must still surface")
}

